// 초경량 Trie 또는 접두사 매칭 + 캐시
const cache = new Map<string, string[]>();

export async function getAutocompleteSuggestions(query: string): Promise<string[]> {
  const clean = query.trim().toLowerCase();
  if (!clean || clean.length < 1) return [];

  if (cache.has(clean)) {
    return cache.get(clean)!;
  }

  // 1. 로컬 영단어 리스트에서 0ms 즉각 매칭
  const localMatches = COMMON_VOCAB_WORDS.filter((w) => w.startsWith(clean)).slice(0, 8);

  // 로컬 매치가 충분하면(5개 이상) 외부 네트워크 요청 없이 즉시 반환 (속도 0ms)
  if (localMatches.length >= 5) {
    cache.set(clean, localMatches);
    return localMatches;
  }

  // 2. 검색어가 2글자 이상이고 로컬 매치가 적으면 무료 Datamuse Sug API 보조 요청
  try {
    const res = await fetch(`https://api.datamuse.com/sug?s=${encodeURIComponent(clean)}&max=8`);
    if (res.ok) {
      const data: Array<{ word: string }> = await res.json();
      const apiWords = data.map((d) => d.word.toLowerCase());
      
      // 중복 제거하여 합치기
      const combined = Array.from(new Set([...localMatches, ...apiWords])).slice(0, 8);
      cache.set(clean, combined);
      return combined;
    }
  } catch (e) {
    // 오프라인이거나 네트워크 실패 시 로컬 매치 반환
  }

  cache.set(clean, localMatches);
  return localMatches;
}
